//go:build generate

// Package main contains code generators for the go-qbittorrent project.
// This generator creates type-safe field update methods for sync operations.
package main

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"log"
	"os"
	"regexp"
	"strings"
)

type FieldInfo struct {
	Name    string
	JSONTag string
	Type    string
	GoType  string
}

type StructInfo struct {
	Name   string
	Fields []FieldInfo
}

func main() {
	// Parse the domain.go file to extract all sync-related structs
	fset := token.NewFileSet()
	domainFile := "domain.go"
	file, err := parser.ParseFile(fset, domainFile, nil, parser.ParseComments)
	if err != nil {
		log.Fatal(err)
	}

	// Structs that are involved in sync operations
	syncStructs := []string{"Torrent", "ServerState", "Category", "TorrentTracker"}
	var structs []StructInfo

	// Find all the sync-related structs
	ast.Inspect(file, func(n ast.Node) bool {
		if ts, ok := n.(*ast.TypeSpec); ok {
			for _, structName := range syncStructs {
				if ts.Name.Name == structName {
					if st, ok := ts.Type.(*ast.StructType); ok {
						fields := parseStructFields(st)
						if len(fields) > 0 {
							structs = append(structs, StructInfo{
								Name:   structName,
								Fields: fields,
							})
						}
					}
				}
			}
		}
		return true
	})

	if len(structs) == 0 {
		log.Fatal("Could not find any sync-related structs")
	}

	// Create output file in the project root
	outputFile := "maindata_updaters_generated.go"
	outFile, err := os.Create(outputFile)
	if err != nil {
		log.Fatal(err)
	}
	defer outFile.Close()

	// Redirect stdout to file
	oldStdout := os.Stdout
	os.Stdout = outFile

	generateAllUpdaters(structs)

	// Restore stdout
	os.Stdout = oldStdout

	fmt.Printf("Generated %s with %d struct updaters\n", outputFile, len(structs))
}

func parseStructFields(st *ast.StructType) []FieldInfo {
	var fields []FieldInfo

	for _, field := range st.Fields.List {
		if field.Names == nil {
			continue // Skip embedded fields
		}

		fieldName := field.Names[0].Name
		fieldType := getFieldType(field.Type)

		// Extract JSON tag
		jsonTag := ""
		if field.Tag != nil {
			tag := field.Tag.Value
			// Use regex to extract json tag value
			re := regexp.MustCompile(`json:"([^"]*)"`)
			matches := re.FindStringSubmatch(tag)
			if len(matches) > 1 {
				jsonTagValue := matches[1]
				// Handle omitempty and other options
				if parts := strings.Split(jsonTagValue, ","); len(parts) > 0 {
					jsonTag = parts[0]
				}
			}
		}

		if jsonTag != "" && jsonTag != "-" {
			fields = append(fields, FieldInfo{
				Name:    fieldName,
				JSONTag: jsonTag,
				Type:    fieldType,
				GoType:  getGoType(field.Type),
			})
		}
	}

	return fields
}

func getFieldType(expr ast.Expr) string {
	switch t := expr.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.SelectorExpr:
		if ident, ok := t.X.(*ast.Ident); ok {
			return ident.Name + "." + t.Sel.Name
		}
	case *ast.ArrayType:
		return "[]" + getFieldType(t.Elt)
	case *ast.MapType:
		return "map[" + getFieldType(t.Key) + "]" + getFieldType(t.Value)
	}
	return "unknown"
}

func getGoType(expr ast.Expr) string {
	switch t := expr.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.SelectorExpr:
		if ident, ok := t.X.(*ast.Ident); ok {
			return ident.Name + "." + t.Sel.Name
		}
	case *ast.ArrayType:
		return "[]" + getGoType(t.Elt)
	case *ast.MapType:
		return "map[" + getGoType(t.Key) + "]" + getGoType(t.Value)
	case *ast.StarExpr:
		return "*" + getGoType(t.X)
	}
	return "interface{}"
}

func generateAllUpdaters(structs []StructInfo) {
	fmt.Println("// Code generated by go generate; DO NOT EDIT.")
	fmt.Println("// Generated by: internal/codegen/generate_maindata_updaters.go")
	fmt.Println()
	fmt.Println("package qbittorrent")
	fmt.Println()
	fmt.Println("import (")
	fmt.Println("\t\"hash/maphash\"")
	fmt.Println("\t\"math\"")
	fmt.Println("\t\"slices\"")
	fmt.Println(")")
	fmt.Println()

	for _, structInfo := range structs {
		generateStructUpdater(structInfo)
		fmt.Println()
	}

	for _, structInfo := range structs {
		switch structInfo.Name {
		case "Torrent":
			generateEqual(structInfo)
			generateChecksum(structInfo)
		case "TorrentTracker":
			generateChecksum(structInfo)
		}
	}
}

// generateEqual writes a function that reports whether two values of the
// struct hold the same values. A full sync update keeps a torrent object when
// it is equal.
func generateEqual(structInfo StructInfo) {
	name := structInfo.Name
	fmt.Printf("// %sEqual reports whether a and b hold the same values.\n", lowerFirst(name))
	fmt.Printf("func %sEqual(a, b *%s) bool {\n", lowerFirst(name), name)
	fmt.Print("\treturn ")
	for i, field := range structInfo.Fields {
		if i > 0 {
			fmt.Print(" &&\n\t\t")
		}
		switch {
		case strings.HasPrefix(field.GoType, "*"):
			fmt.Printf("equalPtr(a.%s, b.%s)", field.Name, field.Name)
		case strings.HasPrefix(field.GoType, "[]"):
			fmt.Printf("slices.Equal(a.%s, b.%s)", field.Name, field.Name)
		default:
			fmt.Printf("a.%s == b.%s", field.Name, field.Name)
		}
	}
	fmt.Print("\n}\n\n")
}

// generateChecksum writes a function that writes each field of the struct to
// a maphash.Hash. A sealed sync snapshot keeps the checksum of each torrent.
func generateChecksum(structInfo StructInfo) {
	name := structInfo.Name
	fmt.Printf("// write%sChecksum writes each field of v to h.\n", name)
	fmt.Printf("func write%sChecksum(h *maphash.Hash, v *%s) {\n", name, name)
	for _, field := range structInfo.Fields {
		switch field.GoType {
		case "string", "TorrentState":
			fmt.Printf("\tchecksumString(h, string(v.%s))\n", field.Name)
		case "int64", "int", "TrackerStatus":
			fmt.Printf("\tchecksumUint(h, uint64(v.%s))\n", field.Name)
		case "float64":
			fmt.Printf("\tchecksumUint(h, math.Float64bits(v.%s))\n", field.Name)
		case "float32":
			fmt.Printf("\tchecksumUint(h, uint64(math.Float32bits(v.%s)))\n", field.Name)
		case "bool":
			fmt.Printf("\tchecksumBool(h, v.%s)\n", field.Name)
		case "*bool":
			fmt.Printf("\tchecksumBool(h, v.%s != nil)\n", field.Name)
			fmt.Printf("\tif v.%s != nil {\n", field.Name)
			fmt.Printf("\t\tchecksumBool(h, *v.%s)\n", field.Name)
			fmt.Printf("\t}\n")
		case "[]TorrentTracker":
			fmt.Printf("\tchecksumUint(h, uint64(len(v.%s)))\n", field.Name)
			fmt.Printf("\tfor i := range v.%s {\n", field.Name)
			fmt.Printf("\t\twriteTorrentTrackerChecksum(h, &v.%s[i])\n", field.Name)
			fmt.Printf("\t}\n")
		default:
			log.Fatalf("Unhandled checksum type: %s for field %s - add proper handling", field.GoType, name+"."+field.Name)
		}
	}
	fmt.Print("}\n\n")
}

func lowerFirst(s string) string {
	return strings.ToLower(s[:1]) + s[1:]
}

func generateStructUpdater(structInfo StructInfo) {
	structName := structInfo.Name
	mapName := fmt.Sprintf("%sFieldUpdaters", strings.ToLower(structName))

	// Generate discrete updater functions for each field
	for _, field := range structInfo.Fields {
		funcName := fmt.Sprintf("update%s%s", structName, field.Name)
		fmt.Printf("// %s updates the %s field of %s\n", funcName, field.Name, structName)
		fmt.Printf("func %s(val interface{}, obj *%s) {\n", funcName, structName)
		generateFieldUpdateLogic(structName, field)
		fmt.Printf("}\n\n")
	}

	// Generate global map that references the discrete functions
	fmt.Printf("// Precomputed field updaters for %s - created once at package init\n", structName)
	fmt.Printf("var %s = map[string]func(val interface{}, obj *%s){\n", mapName, structName)

	for _, field := range structInfo.Fields {
		funcName := fmt.Sprintf("update%s%s", structName, field.Name)
		fmt.Printf("\t\"%s\": %s,\n", field.JSONTag, funcName)
	}

	fmt.Printf("}\n\n")

	// Generate the update function that uses the global map
	methodName := fmt.Sprintf("update%sFields", structName)
	fmt.Printf("// %s updates only the fields that are present in the update map\n", methodName)
	fmt.Printf("func %s(obj *%s, updateMap map[string]interface{}) {\n", methodName, structName)
	fmt.Println("\t// Update only fields that are present in the map using precomputed updaters")
	fmt.Printf("\tfor fieldName, val := range updateMap {\n")
	fmt.Printf("\t\tif updater, exists := %s[fieldName]; exists {\n", mapName)
	fmt.Println("\t\t\tupdater(val, obj)")
	fmt.Println("\t\t}")
	fmt.Println("\t}")
	fmt.Println("}")
}

func generateFieldUpdateLogic(structName string, field FieldInfo) {
	goType := field.GoType

	switch goType {
	case "string":
		fmt.Printf("\tif %s, ok := val.(string); ok {\n", strings.ToLower(field.Name[:1]))
		fmt.Printf("\t\tobj.%s = %s\n", field.Name, strings.ToLower(field.Name[:1]))
		fmt.Printf("\t}\n")
	case "int64":
		fmt.Printf("\tif %s, ok := val.(float64); ok {\n", strings.ToLower(field.Name[:1]))
		fmt.Printf("\t\tobj.%s = int64(%s)\n", field.Name, strings.ToLower(field.Name[:1]))
		fmt.Printf("\t}\n")
	case "int":
		fmt.Printf("\tif %s, ok := val.(float64); ok {\n", strings.ToLower(field.Name[:1]))
		fmt.Printf("\t\tobj.%s = int(%s)\n", field.Name, strings.ToLower(field.Name[:1]))
		fmt.Printf("\t}\n")
	case "float64":
		fmt.Printf("\tif %s, ok := val.(float64); ok {\n", strings.ToLower(field.Name[:1]))
		fmt.Printf("\t\tobj.%s = %s\n", field.Name, strings.ToLower(field.Name[:1]))
		fmt.Printf("\t}\n")
	case "float32":
		fmt.Printf("\tif %s, ok := val.(float64); ok {\n", strings.ToLower(field.Name[:1]))
		fmt.Printf("\t\tobj.%s = float32(%s)\n", field.Name, strings.ToLower(field.Name[:1]))
		fmt.Printf("\t}\n")
	case "bool":
		fmt.Printf("\tif %s, ok := val.(bool); ok {\n", strings.ToLower(field.Name[:1]))
		fmt.Printf("\t\tobj.%s = %s\n", field.Name, strings.ToLower(field.Name[:1]))
		fmt.Printf("\t}\n")
	case "*bool":
		fmt.Printf("\tif %s, ok := val.(bool); ok {\n", strings.ToLower(field.Name[:1]))
		fmt.Printf("\t\tobj.%s = &%s\n", field.Name, strings.ToLower(field.Name[:1]))
		fmt.Printf("\t}\n")
	case "*CategoryDownloadPath":
		// download_path is null (inherit), false (disabled), true or a path
		// string (enabled). Null must reset the field to nil, so this case does
		// not skip a nil value the way the others do.
		fmt.Printf("\tif %s, ok := parseCategoryDownloadPath(val); ok {\n", strings.ToLower(field.Name[:1]))
		fmt.Printf("\t\tobj.%s = %s\n", field.Name, strings.ToLower(field.Name[:1]))
		fmt.Printf("\t}\n")
	case "TorrentState":
		fmt.Printf("\tif %s, ok := val.(string); ok {\n", strings.ToLower(field.Name[:1]))
		fmt.Printf("\t\tobj.%s = TorrentState(%s)\n", field.Name, strings.ToLower(field.Name[:1]))
		fmt.Printf("\t}\n")
	case "TrackerStatus":
		// TrackerStatus is an int-based enum
		fmt.Printf("\tif %s, ok := val.(float64); ok {\n", strings.ToLower(field.Name[:1]))
		fmt.Printf("\t\tobj.%s = TrackerStatus(int(%s))\n", field.Name, strings.ToLower(field.Name[:1]))
		fmt.Printf("\t}\n")
	case "[]TorrentTracker":
		// Handle slice of TorrentTracker with recursive update logic
		fmt.Printf("\tif %s, ok := val.([]interface{}); ok {\n", strings.ToLower(field.Name[:1]))
		fmt.Printf("\t\t// Preallocate slice to avoid reallocations\n")
		fmt.Printf("\t\ttrackers := make([]TorrentTracker, 0, len(%s))\n", strings.ToLower(field.Name[:1]))
		fmt.Printf("\t\tfor _, item := range %s {\n", strings.ToLower(field.Name[:1]))
		fmt.Printf("\t\t\tif trackerMap, ok := item.(map[string]interface{}); ok {\n")
		fmt.Printf("\t\t\t\tvar tracker TorrentTracker\n")
		fmt.Printf("\t\t\t\tupdateTorrentTrackerFields(&tracker, trackerMap)\n")
		fmt.Printf("\t\t\t\ttrackers = append(trackers, tracker)\n")
		fmt.Printf("\t\t\t}\n")
		fmt.Printf("\t\t}\n")
		fmt.Printf("\t\tobj.%s = trackers\n", field.Name)
		fmt.Printf("\t}\n")
	default:
		// Panic on any unhandled type to ensure we handle all types properly
		log.Fatalf("Unhandled type: %s for field %s - add proper handling", goType, structName+"."+field.Name)
	}
}
